def _find(src, name):
    if src == "mixkit":
        return os.path.join(MIX, f"{name}.wav")
    if src == "oga":
        return os.path.join(OGA, f"{name}.mp3")
    pack, base = name.split("/")
    hits = glob.glob(os.path.join(KEN, pack, "**", base + ".ogg"), recursive=True)
    if not hits:
        raise FileNotFoundError(name)
    return hits[0]


@functools.lru_cache(maxsize=None)
def load(src, name, mono=False):
    x, sr = sf.read(_find(src, name), always_2d=True)
    if sr != SR:
        x = signal.resample_poly(x, SR, sr, axis=0)
    if x.shape[1] == 1:
        x = np.repeat(x, 2, axis=1)
    if mono:
        x = x.mean(axis=1, keepdims=True).repeat(2, axis=1)
    # Trim leading silence to the first sample above −40 dB of the peak (so the onset is at sample 0).
    pk = np.abs(x).max() + 1e-12
    on = int(np.argmax(np.abs(x).max(axis=1) > pk * 0.01))
    x = x[max(0, on - 24) :]
    x = x / pk
    fade = min(len(x), int(0.004 * SR))
    x[-fade:] *= np.linspace(1, 0, fade)[:, None]
    return x


def path_of(src, name):
    return _find(src, name)


@functools.lru_cache(maxsize=None)
def keystroke_slices(kind="clack"):
    """Real keystrokes cut from typing takes: each 90 ms, onset at sample 0. 'heavy' = the loudest third (space/enter)."""
    srcs = BANK["key_clack_src"] if kind != "heavy" else BANK["key_heavy_src"] + BANK["key_clack_src"]
    out = []
    for src, name in srcs:
        x, sr = sf.read(_find(src, name), always_2d=True)
        if sr != SR:
            x = signal.resample_poly(x, SR, sr, axis=0)
        m = x.mean(axis=1)
        e = np.sqrt(np.convolve(m**2, np.ones(48) / 48, mode="same"))
        w = int(0.04 * SR)
        c = np.cumsum(np.concatenate([[0], e]))
        idx = np.arange(len(e))
        lo = np.maximum(0, idx - w)
        prev = (c[idx] - c[lo]) / np.maximum(1, idx - lo)
        hit = (e > 3 * prev + 1e-9) & (e > 0.06 * e.max())
        starts = np.where(hit & ~np.concatenate([[False], hit[:-1]]))[0]
        last = -1e9
        for s in starts:
            if s - last < 0.09 * SR:
                continue
            last = s
            seg = x[max(0, s - 24) : s + int(0.09 * SR)].copy()
            if len(seg) < int(0.05 * SR):
                continue
            pk = np.abs(seg).max()
            seg = seg / (pk + 1e-12)
            seg[-int(0.01 * SR) :] *= np.linspace(1, 0, int(0.01 * SR))[:, None]
            out.append((float(pk), seg, f"{src}:{name}@{s / SR:.3f}s"))
    out.sort(key=lambda t: -t[0])
    n = len(out)
    if kind == "heavy":
        return [o[1:] for o in out[: max(6, n // 4)]]
    return [o[1:] for o in out[n // 6 : n - n // 6]]  # drop the loudest and the weakest sixth
